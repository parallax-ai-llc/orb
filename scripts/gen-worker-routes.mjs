// Generates worker/routes.generated.ts from the api/ tree so the Cloudflare
// Worker routes /api/* exactly like Vercel's filesystem routing did:
// static segments win over [param] segments, files starting with "_" and
// tests are not routes. Run after adding or removing an api/ file:
// `node scripts/gen-worker-routes.mjs` (also runs before `pnpm cf:build`).
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(root, 'api');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    if (!/\.(js|ts)$/.test(name) || name.startsWith('_') || /\.test\./.test(name)) return [];
    return [full];
  });
}

const routes = walk(apiDir).map((file) => {
  const rel = relative(apiDir, file).split(sep).join('/').replace(/\.(js|ts)$/, '');
  const segments = rel.split('/');
  return { file, segments };
});

// Vercel precedence: more static segments first, then longer paths.
const staticCount = (r) => r.segments.filter((s) => !s.startsWith('[')).length;
routes.sort(
  (a, b) =>
    staticCount(b) - staticCount(a) ||
    b.segments.length - a.segments.length ||
    a.segments.join('/').localeCompare(b.segments.join('/')),
);

const imports = routes.map((r, i) => {
  const spec = relative(join(root, 'worker'), r.file).split(sep).join('/');
  return `import * as m${i} from '${spec.startsWith('.') ? spec : `./${spec}`}';`;
});
const entries = routes.map(
  (r, i) => `  { segments: ${JSON.stringify(['api', ...r.segments])}, mod: m${i} },`,
);

writeFileSync(
  join(root, 'worker/routes.generated.ts'),
  `// Generated by scripts/gen-worker-routes.mjs from api/. Do not edit.
/* eslint-disable */
${imports.join('\n')}

export interface ApiRoute {
  segments: string[];
  mod: { default: unknown; config?: { runtime?: string } };
}

export const API_ROUTES: ApiRoute[] = [
${entries.join('\n')}
];
`,
);
console.log(`wrote ${routes.length} routes`);
